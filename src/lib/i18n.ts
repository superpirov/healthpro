/** Поиск по упражнениям с учётом русских меток групп/инвентаря */
export function matchExercise(
  needle: string,
  name: string,
  muscleGroup: string,
  equipment: string,
): boolean {
  if (!needle) return true
  return (
    name.toLowerCase().includes(needle) ||
    muscleGroup.toLowerCase().includes(needle) ||
    equipment.toLowerCase().includes(needle) ||
    loc('mg', muscleGroup).toLowerCase().includes(needle) ||
    loc('eq', equipment).toLowerCase().includes(needle)
  )
}

